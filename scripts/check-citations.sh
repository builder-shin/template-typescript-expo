#!/usr/bin/env bash
# 사라질 자리를 가리키는 인용을 찾는다. 루트 AGENTS.md 의 "사라질 자리를
# 인용하지 마라" 절이 규칙이고, 게이트의 [5/9] 단계가 이 스크립트를 부른다.
#
#   ./scripts/check-citations.sh <대상> [<대상>...]
#
# ## 종료 코드 계약
#
#   0  위반 없음
#   1  위반을 찾았다 - 무엇을 찾았는지 stdout 에 그대로 찍는다
#   1  grep 이 오류(2)로 죽었거나 대상이 실재하지 않는다 - stderr 로 구별되게 낸다
#   1  인자가 하나도 없다 - stderr 로 사용법을 낸다
#
# 즉 **0 이 아니면 초록이 아니다.** 세 가지 빨강을 하나의 코드로 합치되 메시지를
# 다르게 내는 이유는, 부르는 쪽(check.sh)이 `if` 하나로 판정할 수 있어야 하고
# 사람은 stderr 를 읽고 어느 빨강인지 알아야 하기 때문이다.
#
# ## 왜 대상을 인자로 받는가 - 조용한 기본값을 두지 않는다
#
# 이 스크립트에 `app components lib test proxy.ts` 를 기본값으로 심으면 대상
# 집합이 **두 곳에 각각** 살게 되고, check.sh 쪽만 좁혀도 여기서는 여전히 넓은
# 집합이 도는(또는 그 반대의) 조용한 어긋남이 생긴다. 대상은 부르는 쪽이 전부
# 명시한다. 인자가 없으면 아무것도 훑지 않고 죽는다 - "인자를 못 넘겼는데 초록"
# 이 이 파일이 막으려는 바로 그 모양이기 때문이다.
#
# 대상 경로는 **호출자의 현재 디렉터리 기준**이다. 이 스크립트는 cd 하지 않는다.
#
# ## 왜 grep 의 종료 코드 셋을 명시적으로 가르는가
#
# 앞선 판은 `if grep …; then` 이었다. `set -euo pipefail` 아래에서 그 형태는
# **비영을 전부 "매치 없음" 으로 읽는다.** GNU grep 의 계약은 0=매치 / 1=매치
# 없음 / **2=오류** 인데 `if` 는 1 과 2 를 구별하지 못한다. 그래서 다섯 대상 중
# 하나만 사라져도(디렉터리 개명 · Next 의 흔한 src/ 이전 · 대상 목록의 오타)
# grep 이 2 로 죽고 게이트는 **초록**이 됐다 - 남은 디렉터리에 실제 위반이 있어
# 그 위반이 게이트 자신의 출력에 찍힌 채로도 그랬다(리뷰가 격리 하네스에서 재현).
#
# 그래서 여기서는 rc 를 잡아 case 로 셋을 가른다. `hits=$(...) && rc=0 || rc=$?`
# 는 `set -e` 아래에서 비영 종료가 스크립트를 죽이지 않게 하는 관용구다 -
# AND-OR 목록이라 `set -e` 의 대상이 아니다.
#
# **대상 존재 여부를 미리 `[ -e ]` 로 확인하지 않는 것은 의도다.** 그 선검사를
# 두면 "대상이 없다" 를 그쪽이 먼저 잡아 버려서, 아래 `*)` 갈래를 통째로 지우는
# 뮤턴트가 **살아남는다** - 두 가드가 서로의 뮤턴트를 가려 준다. 대상 부재를
# grep 의 rc=2 하나로만 관측하면 그 갈래를 지우는 순간 테스트가 죽는다
# (test/unit/scripts/check-citations.test.ts).
#
# ## 왜 패턴이 `superpowers` 가 아닌가
#
# `docs/superpowers/` 는 **커밋되는 자리**라 걸리면 안 된다(오늘 다섯 대상 아래에
# 그 인용이 30자리 살아 있다). 패턴이 잡는 것은 선행 점이 붙은 `.superpowers/`
# 와, 점 없이 쓰인 `superpowers/sdd` 둘이다. 선행 점이 두 세계를 가른다.
#
# ## 이 검사를 재는 테스트는 픽스처 문자열을 이어붙여 만들어야 한다
#
# 검사 대상에 `test/` 가 들어 있어서, 이 패턴을 재는 테스트 파일 자신이 픽스처를
# 문자열 리터럴로 적으면 **그 파일이 이 검사에 걸린다.** 예외 장치(--exclude ·
# 허용 목록 · check-ignore 주석)는 하나도 없다 - 일부러 두지 않았다. 대신
# 픽스처를 `'task-' + '9' + '-report.md'` 처럼 이어붙여 만든다. 이것은 발견돼야만
# 알 수 있는 암묵지가 아니라 여기와 루트 AGENTS.md 의 R21 절에 적힌 계약이다.
set -euo pipefail

# 금지 패턴. 갈래 다섯이고, 각 갈래를 지우는 뮤턴트를 죽이는 픽스처가
# test/unit/scripts/check-citations.test.ts 에 갈래마다 하나씩 있다.
#
#   task-N-(report|review|brief).md  세션이 끝나면 사라지는 태스크 문서
#   \.superpowers/                   계획 종료와 함께 사라지는 트리 전체
#   superpowers/sdd                  선행 점 없이 쓴 같은 자리
#   scratchpad                       세션 스크래치패드
#   guard-rules\.md                  세션이 만들어 쓰고 버리는 규칙 파일
PATTERN='task-[0-9]*-(report|review|brief)\.md|\.superpowers/|superpowers/sdd|scratchpad|guard-rules\.md'

if [ "$#" -eq 0 ]; then
  echo "사용법: $0 <대상> [<대상>...]" >&2
  echo "훑을 대상을 하나도 주지 않았다 - 아무것도 검사하지 않고 죽는다." >&2
  exit 1
fi

hits=$(grep -rnE "$PATTERN" "$@") && rc=0 || rc=$?

case "$rc" in
  0)
    printf '%s\n' "$hits"
    echo ""
    echo "위 자리가 사라질 문서를 가리킨다 - 계획·세션이 끝나면 죽은 링크가 된다." >&2
    echo "근거는 사실 문장으로 적고, 문서가 필요하면 docs/superpowers/ 를 가리켜라." >&2
    exit 1
    ;;
  1)
    exit 0
    ;;
  *)
    echo "" >&2
    echo "grep 이 오류(exit $rc)로 죽었다 - 검사 대상이 실재하지 않는가?" >&2
    echo "훑으려 한 대상: $*" >&2
    echo "이 단계는 '매치 없음'과 '검사 자체가 실패함'을 구별한다 - 후자는 빨강이다." >&2
    exit 1
    ;;
esac
