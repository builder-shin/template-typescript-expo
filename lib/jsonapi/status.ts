/**
 * 백엔드가 답했지만 그 요청을 판정하지 않은 HTTP 상태 - 서버 쪽 실패(5xx), 요청 시간 초과(408), 너무 많은
 * 요청(429). 응답은 왔지만 "이 토큰이 틀렸다", "이 자원이 없다", "이 입력이 틀렸다" 를 말한 것이 아니라서 같은
 * 요청을 잠시 뒤에 다시 보내면 달라질 수 있다. 나머지 4xx 는 백엔드가 읽고 판정한 답이다.
 *
 * 이 저장소가 더한 파일이다(복사본이 아니다) - 한 규칙을 두 곳이 쓴다:
 *
 * - 회전 응답의 해석(`lib/auth/rotation.ts`): 판정하지 않은 응답이면 세션을 지우지 않는다. 판정한 거절만
 *   지운다(스펙 7.2).
 * - 조회의 `queryFn`(`lib/resources/screen-state.ts` 의 `throwIfUnreachable`): 판정하지 않은 응답이면 던져서
 *   읽은 데이터를 두고 다시 시도를 붙인다. 판정한 오류 문서는 값이다(스펙 9.3).
 *
 * 상태 0 은 여기 들지 않는다 - `client.ts` 가 응답이 없었다고 지어낸 합성 오류의 표시이고(`isSyntheticError`),
 * 응답이 아예 없었으니 "답했지만" 이 아니다. 두 소비자가 그것을 따로 가른다.
 */
export function isUnjudgedStatus(status: number): boolean {
  return status >= 500 || status === 408 || status === 429
}
