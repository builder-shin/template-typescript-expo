-- E2E 씨앗 데이터 - 목록·필터·정렬·페이지네이션·상세가 볼 행들.
--
-- `docker-compose.e2e.yml` 의 `seed` 서비스가 마이그레이션 직후 돌린다.
-- 게이트는 매 실행 `down -v` 로 볼륨을 지우므로 이 파일이 그 실행의 데이터
-- 전부다.
--
-- ## `ON CONFLICT DO NOTHING` 이 지키는 것 — **"한 번만 돈다" 가 아니다**
--
-- 아래 네 INSERT 의 `ON CONFLICT` 절을 "어차피 빈 DB 니까 장식" 으로 읽고
-- 지우지 마라. **실측하면 `docker compose up --wait` 은 이미 끝난 `seed`
-- 컨테이너를 다시 돌린다** — `E2E_KEEP_STACK=1` 로 같은 스택 위에서 두 번째
-- 실행을 하면 그 로그가 `INSERT 0 0` ×4 다. 그 절이 없으면 두 번째 실행이
-- 기본 키 충돌로 죽고, 죽는 자리가 `seed` 라 **스택이 아예 뜨지 않는다.**
-- 조사하려고 스택을 남겨 둔 사람이 정확히 그 상황을 만난다.
--
-- ## 왜 HTTP 가 아니라 SQL 인가 (D3 Task 7 의 설계 결정)
--
-- 분류(`categories`)와 라벨(`tags`)에는 **쓰기 라우트가 아예 없다**(계획서
-- R-5). 즉 HTTP 로는 만들 수 없다. 그런데 목록 표의 열 여섯 중 둘이 그
-- 관계이고, 상세 항목 여덟 중 둘도 그것이다 - 관계 없이 시드하면 E2E 가
-- 표의 절반을 못 본다. 예제(`examples`)만 HTTP 로 만드는 절충도 가능하지만,
-- 그러면 시드가 두 채널로 갈리면서 "무엇이 어디서 만들어졌나"를 사람이
-- 추적해야 한다.
--
-- 대가는 **백엔드의 DB 스키마에 붙는 결합**이다. 감수하는 근거: 스키마가
-- 바뀌면 이 파일은 psql 오류로 **즉시, 시끄럽게** 죽는다(`ON_ERROR_STOP=1`) -
-- 게이트가 초록인 채로 틀리는 모양이 아니다. D5 의 3-백엔드 매트릭스는 세
-- 백엔드가 각자 다른 DB 를 쓰므로 어차피 백엔드별 시드가 필요하다.
--
-- 컨테이너가 가진 `db/seeds.py` 는 쓰지 않았다 - **예제가 한 건뿐**이라
-- 정렬·페이지 이동을 잴 수 없고, 그 값들("기본 카테고리"·"JSON:API 예시")은
-- 이 저장소가 아니라 백엔드 저장소가 소유해서 언제 바뀌어도 이쪽은 모른다.
--
-- ## 격리 - 왜 이 데이터가 고정이어도 되는가
--
-- D3 는 **읽기 전용**이라 어느 테스트도 이 행들을 바꾸지 않는다. 서로를
-- 흔들 수 있는 것은 나중에 쓰기를 하는 D4 의 테스트뿐인데, 목록 단언은 아래
-- `probe-seed` 접두사로 좁혀서 본다(`filter[title][contains]`) - 다른 테스트가
-- 만든 행은 그 필터에 걸리지 않는다. D2 가 테스트마다 고유한 이메일로 얻은
-- 격리를, 목록에서는 **제품 자신의 필터**로 얻는다.
--
-- **좁힐 수 없는 자리가 셋 있다**(필터가 사라진 것을 보이는 것이 목적인
-- 테스트들). 그쪽은 씨앗 행만 걸러 보는 다른 방어를 쓴다 -
-- `test/e2e/examples.spec.ts` 머리말의 "좁힐 수 없는 자리 셋" 절이 정본이다.
--
-- **D4 에게:** 이 접두사(`probe-seed`)를 쓰지 마라 - 여섯 건의 제목만이
-- 아니라 **접두사 전체**다. 그것만 지키면 D3 의 테스트가 D4 의 행을 보지
-- 않는다. 새 행에는 다른 접두사를 쓰고, 그 접두사로 좁혀서 단언해라.
--
-- ## 값을 고른 규칙
--
-- **프로덕션 상수와 같은 값을 쓰지 않는다**(이 저장소에서 열 번 넘게 나온
-- 결함). id 는 백엔드 시드(`00000000-…`)와 겹치지 않는 패턴이고, 이름은
-- 전부 `프로브`/`probe-seed` 로 시작한다.
--
-- 그리고 **정렬 키 넷이 서로 다른 순서를 내도록** 값을 배치했다:
--
--   | 정렬                    | 순서                                   |
--   | ----------------------- | -------------------------------------- |
--   | `-createdAt`(기본 정렬) | alpha charlie echo foxtrot bravo delta  |
--   | `title`                 | alpha bravo charlie delta echo foxtrot  |
--   | `-score`                | foxtrot bravo delta echo alpha charlie  |
--   | `-updatedAt`            | delta bravo foxtrot echo charlie alpha  |
--
-- 넷이 같은 순서를 내면 "정렬 키를 바꿔치기한" 결함이 화면에서 보이지 않는다.
-- 특히 `updated_at` 을 `created_at` 과 나란한 값으로 두면 `-updatedAt` 이
-- 기본 정렬과 같은 순서가 되어 **정렬 메뉴의 마지막 항목이 아무것도 재지
-- 못한다** - 그래서 일부러 뒤집힌 순서를 주었다.
--
-- `status` 정렬은 순서를 단언하지 않는다. Postgres enum 의 정렬은 알파벳순이
-- 아니라 **선언 순서**(draft·active·archived)라 그 값은 백엔드 저장소의
-- 것이고, 세 백엔드가 같으리라는 근거가 없다(D5 가 잴 자리다).

BEGIN;

-- 분류 둘. `name` 하나뿐인 자원이다(R-5).
INSERT INTO categories (id, name, created_at, updated_at)
VALUES
  ('11110000-0000-4000-8000-000000000001', '프로브 분류 하나',
   '2026-03-01T00:00:00+00:00', '2026-03-01T00:00:00+00:00'),
  ('11110000-0000-4000-8000-000000000002', '프로브 분류 둘',
   '2026-03-01T00:00:00+00:00', '2026-03-01T00:00:00+00:00')
ON CONFLICT (id) DO NOTHING;

-- 라벨 둘.
INSERT INTO tags (id, name, created_at, updated_at)
VALUES
  ('22220000-0000-4000-8000-000000000001', '프로브 라벨 하나',
   '2026-03-01T00:00:00+00:00', '2026-03-01T00:00:00+00:00'),
  ('22220000-0000-4000-8000-000000000002', '프로브 라벨 둘',
   '2026-03-01T00:00:00+00:00', '2026-03-01T00:00:00+00:00')
ON CONFLICT (id) DO NOTHING;

-- 예제 여섯.
--
-- `created_at` 과 `updated_at` 을 **다른 값**으로 둔다 - 상세에만 있는
-- `수정` 항목이 `생성` 을 베껴 그리는 결함을 화면에서 구별할 수 있어야 한다.
--
-- 시각을 `05:06:07Z` 로 잡은 것도 의도다. `web` 컨테이너의 `TZ` 는 UTC 가
-- 아닌데(compose 파일의 그 줄) 화면은 UTC 로 그리므로, 로컬 시각으로 그리는
-- 결함이 들어오면 **날짜까지** 달라진다.
--
-- charlie 의 점수가 `0` 인 것도 의도다 - 빈 값과 `0` 을 구별하지 못하는
-- 결함(falsy 검사)이 그 행에서 드러난다.
INSERT INTO examples (id, title, description, status, score, category_id, created_at, updated_at)
VALUES
  ('33330000-0000-4000-8000-00000000000a', 'probe-seed alpha',
   NULL, 'draft', 12, NULL,
   '2026-04-06T05:06:07+00:00', '2026-04-11T01:02:03+00:00'),
  ('33330000-0000-4000-8000-00000000000b', 'probe-seed bravo',
   E'프로브 설명 첫 줄\n프로브 설명 둘째 줄', 'active', 77,
   '11110000-0000-4000-8000-000000000001',
   '2026-04-02T05:06:07+00:00', '2026-04-15T01:02:03+00:00'),
  ('33330000-0000-4000-8000-00000000000c', 'probe-seed charlie',
   NULL, 'archived', 0, '11110000-0000-4000-8000-000000000002',
   '2026-04-05T05:06:07+00:00', '2026-04-12T01:02:03+00:00'),
  ('33330000-0000-4000-8000-00000000000d', 'probe-seed delta',
   NULL, 'active', 63, NULL,
   '2026-04-01T05:06:07+00:00', '2026-04-16T01:02:03+00:00'),
  ('33330000-0000-4000-8000-00000000000e', 'probe-seed echo',
   NULL, 'draft', 38, '11110000-0000-4000-8000-000000000001',
   '2026-04-04T05:06:07+00:00', '2026-04-13T01:02:03+00:00'),
  ('33330000-0000-4000-8000-00000000000f', 'probe-seed foxtrot',
   NULL, 'archived', 94, NULL,
   '2026-04-03T05:06:07+00:00', '2026-04-14T01:02:03+00:00')
ON CONFLICT (id) DO NOTHING;

-- 참조 목록 100건 천장을 **실제로 넘기는** 채움 행 (D4 브랜치 리뷰 Critical-1).
--
-- `referenceRequest`(lib/resources/view.ts)는 `sort=name&page[size]=100` 을
-- 보내고 `page[number]` 를 보내지 않는다 - 참조 자원이 100건을 넘으면
-- 이름순 101번째부터는 선택기에 **없다.** 그 세계가 "선택된 것이 목록 밖"
-- 이라는 상태를 만들고, 그것이 수정 저장에서 관계를 지우던 결함이었다
-- (test/e2e/examples-write.spec.ts 의 "참조 목록에서 잘려 나간..." 테스트).
--
-- **이 상태는 브라우저에서 만들 수 없다.** 참조 조회는 Next 서버가 백엔드
-- (`http://api:4000`)에 직접 보내는 요청이라 `page.route` 가 닿지 못한다 -
-- 유일하게 정직한 길이 실제로 천장을 넘기는 것이다.
--
-- ## 이름을 `힣` 로 시작시킨 이유
--
-- 정렬은 `name` 오름차순이다. 채움 행이 **뒤에** 와야 위의 `프로브 분류
-- 하나`·`프로브 라벨 하나` 가 첫 100건 안에 남고 기존 테스트가 그대로
-- 돈다. `힣`(U+D7A3)은 `프`(U+D504)보다 뒤이고, 코드포인트순·바이트순·
-- 자모순 어느 대조 규칙에서도 그렇다.
--
-- ## 왜 99건인가
--
-- 분류·라벨 각각 위에 둘씩 있으므로 99건을 더하면 101건이 된다. 첫 100건은
-- `... 둘` · `... 하나` · `힣넘침*-000` ~ `-097` 이고 **`-098` 하나만
-- 밖으로 밀린다** - 그 한 건이 테스트가 쓰는 "목록 밖 항목" 이다. 잘림이
-- 실제로 일어났다는 것(`links.next`)도 함께 켜진다.
--
-- 이 행들은 어떤 화면의 목록에도 나오지 않는다 - 분류·라벨에는 컬렉션
-- 화면이 없고(R-5) 예제에 붙지도 않는다. 즉 D3 의 목록·필터·정렬·상세
-- 단언은 이 행들을 보지 못한다.
INSERT INTO categories (id, name, created_at, updated_at)
SELECT
  ('11119999-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid,
  '힣넘침분류-' || lpad(n::text, 3, '0'),
  '2026-03-01T00:00:00+00:00'::timestamptz,
  '2026-03-01T00:00:00+00:00'::timestamptz
FROM generate_series(0, 98) AS n
ON CONFLICT (id) DO NOTHING;

INSERT INTO tags (id, name, created_at, updated_at)
SELECT
  ('22229999-0000-4000-8000-' || lpad(n::text, 12, '0'))::uuid,
  '힣넘침라벨-' || lpad(n::text, 3, '0'),
  '2026-03-01T00:00:00+00:00'::timestamptz,
  '2026-03-01T00:00:00+00:00'::timestamptz
FROM generate_series(0, 98) AS n
ON CONFLICT (id) DO NOTHING;

